"use client";
import { useState } from "react";
import type { Lesson } from "@/lib/algebra/engine";
import { Math as M, Prose } from "./Math";
import {
  leftCyclicModule,
  rightCyclicModule,
  tensorPresentation,
} from "@/lib/algebra/tensor-balancing";

export function TensorBalancingLab({ lesson }: { lesson: Lesson }) {
  const [rightModulus, setRightModulus] = useState(2);
  const [leftModulus, setLeftModulus] = useState(4);
  const [scalar, setScalar] = useState(3);
  const [u, setU] = useState(1);
  const [v, setV] = useState(1);
  const [prediction, setPrediction] = useState("");
  const [revealed, setRevealed] = useState(false);
  const [failure, setFailure] = useState(false);
  const model = tensorPresentation(
    rightCyclicModule(rightModulus),
    leftCyclicModule(leftModulus),
    scalar,
    u,
    v,
  );
  const reset = () => {
    setPrediction("");
    setRevealed(false);
    setFailure(false);
  };
  return (
    <div className="foundation-lab">
      <p>
        <Prose>{String.raw`What does the balancing relation identify? $U=\mathbb Z/m\mathbb Z$ is a right $\mathbb Z$-module, $V=\mathbb Z/n\mathbb Z$ is a left $\mathbb Z$-module. Their tensor product is an abelian group generated by $t=[1]\otimes[1]$, with relations $mt=0$ and $nt=0$. The right/left order matters for a noncommutative base ring.`}</Prose>
      </p>
      <M block>
        {
          "(ur)\\otimes v=u\\otimes(rv),\\qquad (\\mathbb Z/m)\\otimes_{\\mathbb Z}(\\mathbb Z/n)\\cong\\mathbb Z/\\gcd(m,n)"
        }
      </M>
      <div className="lab-controls">
        <label>
          Right module{" "}
          <M focusable={false}>{String.raw`U=\mathbb Z/m\mathbb Z`}</M>; choose{" "}
          <M focusable={false}>{"m"}</M>
          <select
            aria-label="Right module U=ℤ/mℤ; choose m"
            value={rightModulus}
            onChange={(e) => {
              setRightModulus(Number(e.target.value));
              setU(0);
              reset();
            }}
          >
            {[2, 3, 4, 6, 8, 12].map((m) => (
              <option key={m} value={m}>
                {m}
              </option>
            ))}
          </select>
        </label>
        <label>
          Left module{" "}
          <M focusable={false}>{String.raw`V=\mathbb Z/n\mathbb Z`}</M>; choose{" "}
          <M focusable={false}>{"n"}</M>
          <select
            aria-label="Left module V=ℤ/nℤ; choose n"
            value={leftModulus}
            onChange={(e) => {
              setLeftModulus(Number(e.target.value));
              setV(0);
              reset();
            }}
          >
            {[2, 3, 4, 6, 8, 12].map((n) => (
              <option key={n} value={n}>
                {n}
              </option>
            ))}
          </select>
        </label>
        <label>
          Integer scalar <M focusable={false}>{String.raw`r`}</M>
          <select
            aria-label="Integer scalar r"
            value={scalar}
            onChange={(e) => {
              setScalar(Number(e.target.value));
              reset();
            }}
          >
            {[0, 1, 2, 3, 4, 6].map((r) => (
              <option key={r} value={r}>
                {r}
              </option>
            ))}
          </select>
        </label>
        <label>
          Right-module vector <M focusable={false}>{String.raw`[u]`}</M>
          <select
            aria-label="Right-module vector [u]"
            value={u}
            onChange={(e) => {
              setU(Number(e.target.value));
              reset();
            }}
          >
            {Array.from({ length: rightModulus }, (_, index) => (
              <option key={index} value={index}>
                [{index}]
              </option>
            ))}
          </select>
        </label>
        <label>
          Left-module vector <M focusable={false}>{String.raw`[v]`}</M>
          <select
            aria-label="Left-module vector [v]"
            value={v}
            onChange={(e) => {
              setV(Number(e.target.value));
              reset();
            }}
          >
            {Array.from({ length: leftModulus }, (_, index) => (
              <option key={index} value={index}>
                [{index}]
              </option>
            ))}
          </select>
        </label>
      </div>
      <label className="prediction-prompt">
        Predict the order of <M focusable={false}>{"t"}</M> and compare{" "}
        <M focusable={false}>{String.raw`(ur)\otimes v`}</M> with{" "}
        <M focusable={false}>{String.raw`u\otimes(rv)`}</M> before revealing.
        <textarea
          value={prediction}
          onChange={(e) => setPrediction(e.target.value)}
          aria-label="Your mathematical prediction"
        />
      </label>
      <button
        type="button"
        disabled={!prediction.trim()}
        onClick={() => setRevealed(true)}
      >
        Test my prediction
      </button>
      {revealed && (
        <div className="live-mathematics" aria-live="polite">
          <h3>Balanced generator and relation evidence</h3>
          <p>
            <Prose>{String.raw`Relations $${rightModulus}t=0$ and $${leftModulus}t=0$ give $\operatorname{ord}(t)=\gcd(${rightModulus},${leftModulus})=${model.gcd}$. Thus $U\otimes_{\mathbb Z}V\cong\mathbb Z/${model.gcd}\mathbb Z$ with elements $\{${model.tensorElements.join(", ")}\}$.`}</Prose>
          </p>
          <p>
            <Prose>{String.raw`$([${u}]\cdot ${scalar})\otimes[${v}]=[${model.leftRepresentative}]\otimes[${v}]=${model.leftValue}t$; $[${u}]\otimes(${scalar}\cdot[${v}])=[${u}]\otimes[${model.rightRepresentative}]=${model.rightValue}t$. Balance: ${model.balanced ? "equal" : "unequal"}. The pure tensor $[${u}]\otimes[${v}]=${model.pureValue}t$.`}</Prose>
          </p>
          <p>
            <Prose>{String.raw`In $F^2\otimes_F F^2$, $e_1\otimes f_1+e_2\otimes f_2$ has matrix rank $2$, so it is not pure. For finite-dimensional $F$-spaces $V,W$, $V^*\otimes_F W\cong\operatorname{Hom}_F(V,W)$ via $\varphi\otimes w\mapsto(v\mapsto\varphi(v)w)$.`}</Prose>
          </p>
          {failure && (
            <p role="status">
              <Prose>{String.raw`Failure witness: $(\mathbb Z/2\mathbb Z)\otimes_{\mathbb Z}(\mathbb Z/3\mathbb Z)=0$ because $2t=3t=0$ forces $t=0$. Two nonzero factors need not yield a nonzero tensor product.`}</Prose>
            </p>
          )}
          <table>
            <caption>Typed balancing and cyclic tensor relation</caption>
            <thead>
              <tr>
                <th scope="col">Check</th>
                <th scope="col">Value</th>
              </tr>
            </thead>
            <tbody>
              <tr>
                <th scope="row">Right input</th>
                <td>
                  <M>{String.raw`\mathbb Z/${rightModulus}\mathbb Z,\quad u=[${u}]`}</M>
                </td>
              </tr>
              <tr>
                <th scope="row">Left input</th>
                <td>
                  <M>{String.raw`\mathbb Z/${leftModulus}\mathbb Z,\quad v=[${v}]`}</M>
                </td>
              </tr>
              <tr>
                <th scope="row">Generator order</th>
                <td>
                  <M>{String(model.generatorOrder)}</M>
                </td>
              </tr>
              <tr>
                <th scope="row">
                  Right-side balance <M>{String.raw`(ur)\otimes v`}</M>
                </th>
                <td>
                  <M>{`${model.leftValue}t`}</M>
                </td>
              </tr>
              <tr>
                <th scope="row">
                  Left-side balance <M>{String.raw`u\otimes(rv)`}</M>
                </th>
                <td>
                  <M>{`${model.rightValue}t`}</M>
                </td>
              </tr>
            </tbody>
          </table>
        </div>
      )}
      <button
        type="button"
        onClick={() => {
          setRightModulus(2);
          setLeftModulus(3);
          setU(1);
          setV(1);
          setScalar(1);
          setPrediction("The generator may vanish despite nonzero factors.");
          setRevealed(true);
          setFailure(true);
        }}
      >
        Try the zero tensor-product failure
      </button>
      <div className="laboratory-debrief">
        <h3>Theorem debrief and proof boundary</h3>
        <p>
          <Prose>{String.raw`The cyclic presentation is a worked $\mathbb Z$-module computation. For a right $R$-module $U$ and left $R$-module $V$, the universal property says every balanced biadditive map $U\times V\to A$ to an abelian group factors uniquely through $U\otimes_R V$. The finite table illustrates that property; it does not prove it for arbitrary $R$. An external product $\pi\boxtimes\rho$ of $G$- and $H$-representations uses the underlying field tensor with a separate $(G\times H)$-action; its notation and kernel question are distinct.`}</Prose>
        </p>
        <p>
          <Prose>{lesson.title}</Prose> keeps the module sides explicit.
        </p>
      </div>
    </div>
  );
}
